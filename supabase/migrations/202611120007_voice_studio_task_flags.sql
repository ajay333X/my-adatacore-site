CREATE TABLE IF NOT EXISTS public.vs_task_flags(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id uuid NOT NULL REFERENCES public.vs_sessions(id),
 reported_by uuid NOT NULL REFERENCES auth.users(id),
 reason text NOT NULL CHECK(length(trim(reason)) BETWEEN 5 AND 2000),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS vs_task_flags_session_idx ON public.vs_task_flags(session_id,created_at DESC);
ALTER TABLE public.vs_task_flags ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "voice studio flags visible to reporter and admins" ON public.vs_task_flags;
CREATE POLICY "voice studio flags visible to reporter and admins" ON public.vs_task_flags FOR SELECT TO authenticated
 USING(reported_by=(select auth.uid()) OR public.vs_is_admin());
REVOKE ALL ON public.vs_task_flags FROM anon,authenticated;
GRANT SELECT ON public.vs_task_flags TO authenticated;
CREATE OR REPLACE FUNCTION public.vs_flag_task(p_session uuid,p_reason text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE v public.vs_sessions;u uuid:=auth.uid();flag_id bigint;
BEGIN
 SELECT * INTO v FROM public.vs_sessions WHERE id=p_session;
 IF u IS NULL OR v.id IS NULL OR NOT(u=v.actor_a OR u=v.actor_b OR public.vs_is_admin()) THEN RAISE EXCEPTION 'SESSION_ACCESS_DENIED';END IF;
 IF char_length(trim(coalesce(p_reason,''))) NOT BETWEEN 5 AND 2000 THEN RAISE EXCEPTION 'INVALID_FLAG_REASON';END IF;
 INSERT INTO public.vs_task_flags(session_id,reported_by,reason) VALUES (p_session,u,trim(p_reason)) RETURNING id INTO flag_id;
 RETURN flag_id;
END
$function$;
REVOKE ALL ON FUNCTION public.vs_flag_task(uuid,text) FROM public,anon;
GRANT EXECUTE ON FUNCTION public.vs_flag_task(uuid,text) TO authenticated;
